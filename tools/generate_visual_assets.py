#!/usr/bin/env python3
"""Export SVG type marks and the selected generated logo to Flash-only LVGL data."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TYPES = 'normal fighting flying poison ground rock bug ghost steel fire water grass electric psychic ice dragon dark fairy'.split()


def pixels(image):
    rgba = list(image.convert('RGBA').get_flattened_data())
    rgb = bytearray()
    for r, g, b, _ in rgba:
        c = (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
        rgb.extend(c.to_bytes(2, 'little'))
    return bytes(rgb) + bytes(p[3] for p in rgba)


def emit_image(lines, image, name, descriptor=True):
    data = pixels(image)
    lines.append(f'static const uint8_t {name}_pixels[] = {{')
    for i in range(0, len(data), 24):
        lines.append('    ' + ','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    lines.append('};')
    w, h = image.size
    value = f'{{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = {w}, .h = {h}, .stride = {w * 2}}}, .data_size = sizeof({name}_pixels), .data = {name}_pixels}}'
    if descriptor:
        lines.append(f'const lv_image_dsc_t {name} = {value};')
    return value


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--node', default='node')
    parser.add_argument('--resvg', required=True, help='Path to @resvg/resvg-js 2.6.2')
    args = parser.parse_args()
    output = ROOT / 'build/visual-assets'
    output.mkdir(parents=True, exist_ok=True)
    subprocess.run([args.node, str(ROOT / 'tools/render_type_icons.cjs'), args.resvg, str(output)], check=True)
    meta = json.loads((ROOT / 'assets/pokedex/type-icons/source.json').read_text())
    fg = json.loads((output / 'foregrounds.json').read_text())
    lines = ['/* Generated by tools/generate_visual_assets.py. */', '#include "dex_visual_assets.h"']
    hashes = set()
    for size in (20, 24):
        descriptors = ['{.header = {.magic = LV_IMAGE_HEADER_MAGIC}}']
        for name in TYPES:
            im = Image.open(output / f'{name}-{size}.png')
            assert im.size == (size, size)
            assert im.getchannel('A').getextrema() == (0, 255)
            digest = hashlib.sha256(pixels(im)).hexdigest()
            assert digest not in hashes
            hashes.add(digest)
            descriptors.append(emit_image(lines, im, f'dex_type_{name}_{size}', False))
        lines.append(f'const lv_image_dsc_t dex_type_icons_{size}[19] = {{' + ',\n'.join(descriptors) + '};')
    for label, colors in [('colors', meta['colors']), ('foregrounds', fg)]:
        lines.append(f'const uint32_t dex_type_{label}[19] = {{0,' + ','.join('0x' + colors[t][1:] for t in TYPES) + '};')
    # This is a deterministic display export of the selected imagegen asset,
    # not a creative edit: preserve all artwork, aspect ratio and alpha.
    logo_path = ROOT / 'assets/pokedex/pocket-dex-logo.png'
    if logo_path.exists():
        logo = Image.open(logo_path).convert('RGBA')
        logo = logo.crop(logo.getbbox())
        logo.thumbnail((208, 180), Image.Resampling.LANCZOS)
        logo.save(output / 'logo-display.png')
        emit_image(lines, logo, 'dex_logo')
    (ROOT / 'main/dex_visual_assets.c').write_text('\n'.join(lines) + '\n', encoding='utf8')
    print('18 types x 2 sizes: alpha, dimensions and uniqueness PASS; logo:', logo_path.exists())


if __name__ == '__main__':
    main()
