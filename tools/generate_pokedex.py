#!/usr/bin/env python3
"""Generate Flash-resident C tables and an auditable font inventory."""
import argparse
import hashlib
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[1]


def cstr(s):
    return json.dumps(s, ensure_ascii=False)


def generate():
    data = json.loads((ROOT / 'assets/pokedex/catalog.json').read_text(encoding='utf8'))
    lines = ['/* Generated by tools/generate_pokedex.py; edit the input catalog. */',
             '#include "dex_data.h"', 'const dex_entry_t dex_entries[DEX_COUNT + 1] = {', '    {0},']
    indices = []
    for p in data['pokemon']:
        types = p['types'] + [0]
        fields = [cstr(p[k]) for k in ('name', 'initials', 'description', 'description_version')]
        fields += [str(len(indices)), str(len(p['move_indices'])), str(p['height']), str(p['weight']),
                   '{' + ','.join(map(str, p['stats'])) + '}', str(p['gen']), str(types[0]), str(types[1]),
                   str(p['move_gen']), str(p['move_group'])]
        lines.append('    {' + ','.join(fields) + '},')
        indices += p['move_indices']
    lines += ['};', 'const uint16_t dex_move_indices[] = {']
    lines += ['    ' + ','.join(map(str, indices[i:i+24])) + ',' for i in range(0, len(indices), 24)]
    lines += ['};', 'const dex_move_t dex_moves[] = {']
    for m in data['moves']:
        lines.append('    {' + ','.join([cstr(m['name'])] + [str(m[k]) for k in
                    ('id', 'power', 'accuracy', 'pp', 'type_id', 'group')]) + '},')
    lines += ['};', 'const size_t dex_move_variant_count = sizeof(dex_moves) / sizeof(dex_moves[0]);',
              'const char *const dex_types[19] = {' + ','.join(map(cstr, data['types'])) + '};',
              'const char *const dex_groups[26] = {' + ','.join(cstr(data['groups'].get(str(i), '')) for i in range(26)) + '};']
    out = ROOT / 'main/dex_data.c'
    out.write_text('\n'.join(lines) + '\n', encoding='utf8')
    # Include every application source character. ASCII comments only add ASCII;
    # extra Chinese comment characters are harmless and make drift conservative.
    text = ''.join(out.read_text(encoding='utf8'))
    for source in sorted((ROOT / 'main').glob('dex_*.c')):
        text += source.read_text(encoding='utf8')
    chars = sorted({c for c in text if ord(c) >= 32} | set(chr(i) for i in range(32, 127)))
    font_dir = ROOT / 'assets/fonts'
    font_dir.mkdir(exist_ok=True)
    (font_dir / 'pokedex-glyphs.txt').write_text(''.join(chars), encoding='utf8')
    (font_dir / 'pokedex-glyphs.json').write_text(json.dumps([ord(c) for c in chars]), encoding='utf8')
    (ROOT / 'main/dex_glyphs.h').write_text(
        '/* Generated font coverage inventory. */\n#pragma once\n#include <stdint.h>\n'
        'static const uint32_t dex_glyphs[] = {' + ','.join(str(ord(c)) for c in chars) + '};\n', encoding='utf8')
    print('Species:', len(data['pokemon']), 'Relations:', len(indices), 'Glyphs:', len(chars))
    return chars


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--font', type=pathlib.Path)
    p.add_argument('--converter', type=pathlib.Path)
    p.add_argument('--node', default='node')
    args = p.parse_args()
    chars = generate()
    if args.font:
        from fontTools.ttLib import TTFont
        font = TTFont(args.font)
        missing = sorted(set(map(ord, chars)) - set(font.getBestCmap()))
        if missing:
            raise SystemExit('Source font missing: ' + ', '.join(f'U+{c:04X}' for c in missing))
        assert 0x10ffff not in font.getBestCmap()  # Negative coverage control.
        ranges = ','.join(f'0x{ord(c):x}' for c in chars)
        for size in (16, 20):
            subprocess.run([args.node, str(args.converter), '--font', str(args.font),
                            '--range', ranges, '--size', str(size), '--bpp', '2',
                            '--format', 'lvgl', '--no-compress', '--no-kerning',
                            '--lv-font-name', f'dex_font_{size}', '--lv-include', 'lvgl.h',
                            '--output', str(ROOT / f'assets/fonts/dex_font_{size}.c')], check=True)
            # Keep converter metadata without embedding the builder's local paths.
            generated = ROOT / f'assets/fonts/dex_font_{size}.c'
            source = generated.read_text(encoding='utf8')
            source = '\n'.join(
                ' * Generated by tools/generate_pokedex.py; see assets/fonts/font-source.json.'
                if line.startswith(' * Opts:') else line for line in source.splitlines()
            ).rstrip() + '\n'
            generated.write_text(source, encoding='utf8')
        (ROOT / 'assets/fonts/font-source.json').write_text(json.dumps({
            'family': 'Noto Sans CJK SC Regular', 'license': 'SIL OFL 1.1',
            'source': 'https://github.com/notofonts/noto-cjk/tree/main/Sans/OTF/SimplifiedChinese',
            'sha256': hashlib.sha256(args.font.read_bytes()).hexdigest(),
            'converter': 'lv_font_conv@1.5.3', 'sizes': [16, 20], 'bpp': 2,
            'glyphs': len(chars), 'missing_source_glyphs': []}, indent=2) + '\n', encoding='utf8')
